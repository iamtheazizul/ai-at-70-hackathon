// Generate supabase/migrations/0002_seed_sample_store.sql from the fixture in
// src/data/sampleStore.ts.
//
// The fixture is the only complete store description in the repo: 18 drawn
// nodes, 31 edges, 8 aisles with sign variants, 16 sections, 14 products with
// barcodes and shelf locations. Hand-transcribing that into SQL would mean two
// copies drifting apart, so it is generated and regenerated instead. Run after
// changing the fixture:
//
//   npm run gen-seed
//
// The fixture is TypeScript, so it is compiled to a temp directory first. It
// imports nothing at runtime (its only import is `import type`), so the
// compiled file stands alone.

import { spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const SURVEY_DATE = '2026-10-27';
const STORE_ID = 1;

const out = new URL('../supabase/migrations/0002_seed_sample_store.sql', import.meta.url);
const tmp = mkdtempSync(join(tmpdir(), 'shoptimal-seed-'));

try {
  const tsc = spawnSync(
    'npx',
    ['tsc', 'src/data/sampleStore.ts', '--outDir', tmp, '--rootDir', 'src',
     '--module', 'esnext', '--target', 'es2022', '--moduleResolution', 'bundler', '--skipLibCheck'],
    { stdio: 'inherit' },
  );
  if (tsc.status !== 0) {
    console.error('tsc failed on the fixture');
    process.exit(1);
  }

  const { sampleStorePack: pack } = await import(pathToFileURL(join(tmp, 'data/sampleStore.js')).href);

  const q = (v) => (v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
  const n = (v) => (v === undefined || v === null ? 'null' : String(v));
  const L = [];

  L.push('-- ============================================================================');
  L.push('-- GENERATED by scripts/gen-seed.mjs from src/data/sampleStore.ts.');
  L.push('-- Do not edit by hand: run `npm run gen-seed` instead.');
  L.push('--');
  L.push('-- Fixture data, not a surveyed store. Every edge is `measured = true` because');
  L.push('-- the fixture is internally consistent by construction, not because anyone');
  L.push('-- paced it. A real survey sets that column honestly.');
  L.push('--');
  L.push('-- Owns ids 1..N in every table it touches and deletes them before inserting,');
  L.push('-- so re-running replaces the fixture rather than duplicating it. Identity');
  L.push('-- sequences are bumped past the fixture at the end so later real rows do not');
  L.push('-- collide with these.');
  L.push('-- ============================================================================');
  L.push('');
  L.push('-- Cascades to node, edge, aisle, aisle_sign_variant, section, store_pack.');
  L.push(`delete from store where id = ${STORE_ID};`);
  L.push(`-- Products are not store-scoped, so they go by id. Cascades to`);
  L.push('-- product_barcode and product_location.');
  L.push(`delete from product where id between 1 and ${Math.max(...pack.products.map((p) => p.id))};`);
  L.push('');

  L.push('insert into store (id, name, layout_version, surveyed_on, permitted_activities)');
  L.push('  overriding system value values');
  L.push(`  (${STORE_ID}, ${q(pack.storeName)}, ${q(pack.layoutVersion)}, ${q(SURVEY_DATE)}, '{}'::jsonb);`);
  L.push('');

  // node.aisle_id is filled after aisle exists: the two tables reference each other.
  L.push('-- aisle_id is set after the aisles exist; node and aisle reference each other.');
  L.push('insert into node (id, store_id, kind, label, x_metres, y_metres, photo_path)');
  L.push('  overriding system value values');
  L.push(pack.nodes.map((d) =>
    `  (${d.id}, ${STORE_ID}, ${q(d.kind)}, ${q(d.label)}, ${n(d.xMetres)}, ${n(d.yMetres)}, ${q(d.photoPath)})`,
  ).join(',\n') + ';');
  L.push('');

  L.push('insert into aisle (id, store_id, label, reference_end_node, direction_note, is_cold, cold_relaxed)');
  L.push('  overriding system value values');
  L.push(pack.aisles.map((a) =>
    `  (${a.id}, ${STORE_ID}, ${q(a.label)}, ${a.referenceEndNode}, ` +
    `${q('sides named facing from the front-end node')}, ${a.isCold}, ${a.coldRelaxed})`,
  ).join(',\n') + ';');
  L.push('');

  const withAisle = pack.nodes.filter((d) => d.aisleId !== undefined);
  L.push('update node set aisle_id = v.aisle_id from (values');
  L.push(withAisle.map((d) => `  (${d.id}, ${d.aisleId})`).join(',\n'));
  L.push(') as v(node_id, aisle_id) where node.id = v.node_id;');
  L.push('');

  L.push('insert into aisle_sign_variant (aisle_id, variant, kind) values');
  L.push(pack.aisles.flatMap((a) =>
    a.signVariants.map((s) => `  (${a.id}, ${q(s.variant)}, ${q(s.kind)})`),
  ).join(',\n') + ';');
  L.push('');

  L.push('insert into section (id, aisle_id, side, bay, access_node)');
  L.push('  overriding system value values');
  L.push(pack.sections.map((s) =>
    `  (${s.id}, ${s.aisleId}, ${q(s.side)}, ${s.bay}, ${s.accessNode})`,
  ).join(',\n') + ';');
  L.push('');

  // check (a_node < b_node): the table stores each undirected edge once.
  L.push('insert into edge (store_id, a_node, b_node, metres, measured, verified_on) values');
  L.push(pack.edges.map((e) => {
    const [a, b] = e.a < e.b ? [e.a, e.b] : [e.b, e.a];
    return `  (${STORE_ID}, ${a}, ${b}, ${e.metres}, ${e.measured}, ${q(SURVEY_DATE)})`;
  }).join(',\n') + ';');
  L.push('');

  L.push('insert into product (id, name, brand, variant, size_text, category, photo_path)');
  L.push('  overriding system value values');
  L.push(pack.products.map((p) =>
    `  (${p.id}, ${q(p.name)}, ${q(p.brand)}, ${q(p.variant)}, ${q(p.sizeText)}, ${q(p.category)}, ${q(p.photoPath)})`,
  ).join(',\n') + ';');
  L.push('');

  L.push("insert into product_barcode (barcode, product_id, symbology) values");
  L.push(Object.entries(pack.barcodes).map(([code, id]) =>
    `  (${q(code)}, ${id}, 'EAN_13')`,
  ).join(',\n') + ';');
  L.push('');

  L.push('insert into product_location (product_id, section_id, shelf_level, source, verified_on, review_status) values');
  L.push(pack.locations.map((l) =>
    `  (${l.productId}, ${l.sectionId}, ${q(l.shelfLevel)}, ${q(l.source)}, ${q(l.verifiedOn)}, ${q(l.reviewStatus)})`,
  ).join(',\n') + ';');
  L.push('');

  L.push('-- Move each identity sequence past the fixture rows inserted above.');
  for (const t of ['store', 'node', 'aisle', 'aisle_sign_variant', 'section', 'edge', 'product', 'product_location']) {
    L.push(`select setval(pg_get_serial_sequence('${t}', 'id'), (select coalesce(max(id), 1) from ${t}));`);
  }
  L.push('');

  writeFileSync(out, L.join('\n'));
  console.log(
    `wrote ${fileURLBasename(out)}: ${pack.nodes.length} nodes, ${pack.edges.length} edges, ` +
    `${pack.aisles.length} aisles, ${pack.sections.length} sections, ${pack.products.length} products, ` +
    `${Object.keys(pack.barcodes).length} barcodes, ${pack.locations.length} locations`,
  );
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

function fileURLBasename(u) {
  return u.pathname.split('/').pop();
}
